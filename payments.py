from aiogram import types

async def handle_subscribe(call: types.CallbackQuery):
    """
    Обработка нажатия кнопки 'Оформить подписку'.
    Отправляет инструкцию по оплате.
    """
    await call.message.answer(
        "💳 **Оформление подписки**\n\n"
        "Для активации Premium-доступа переведи 300₽ на карту:\n"
        "`5534 2000 5167 0180`\n\n"
        "После перевода напиши админу: @Yuli_kor\n\n"
        "_Подписка активируется вручную администратором_"
    )
    await call.answer("ℹ️ Инструкция по оплате отправлена")